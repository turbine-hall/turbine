import { closeSync, existsSync, fchmodSync, lstatSync, mkdirSync, openSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import {
  RepoSnapshotSchema,
  contentHashText,
  hasUnsafeKey,
  shortSnapshotId,
  type Convention,
  type FactSource,
  type RepoSnapshot,
} from '@turbine-hall/turbine-contracts';
import type { LintIssue } from '../docs/lint.js';
import { isGitIgnored, trackedPaths } from './git-read.js';

/**
 * Renders a snapshot to `.turbine/context/`:
 *   snapshot.json  the snapshot itself
 *   PROJECT.md     a generated "Facts" section (header + content hash), never hand-edited
 * `lintProjectContext` reports any hand edit, so generated facts cannot drift from the snapshot.
 */

export const CONTEXT_DIR = 'context';
const FILE_HEADER =
  '<!-- GENERATED by `turbine understand`. The Facts section is overwritten on every run and checked by `turbine lint`; do not edit it by hand. -->';
// Markers count only when they are a whole line (so text that merely quotes one is left alone), and
// the same line-based grammar is used to count them and to find the section to replace.
// A file edited on Windows has CRLF line endings: "\r?" lets the same grammar read them.
const BEGIN = /^<!-- turbine:facts begin ([^>]*?) -->\r?$/m;
const SECTION = /^<!-- turbine:facts begin ([^>]*?) -->\r?\n([\s\S]*?)\r?\n<!-- turbine:facts end -->\r?$/m;
/** Section body with line endings normalised, so the hash does not depend on the platform that wrote it. */
const bodyOf = (m: RegExpExecArray) => m[2]!.replace(/\r\n/g, '\n');

export function contextPaths(projectRoot: string) {
  const dir = join(projectRoot, '.turbine', CONTEXT_DIR);
  return { dir, snapshot: join(dir, 'snapshot.json'), project: join(dir, 'PROJECT.md') };
}

const cite = (s: FactSource) => `${s.path}@${s.blob.slice(0, 8)}${s.lines ? `:L${s.lines.start}${s.lines.end !== s.lines.start ? `-${s.lines.end}` : ''}` : ''}`;
const CAP = 60;

/** A statement is one Markdown line: any line break inside it (from a file's content) becomes a space. */
const oneLine = (t: string) => t.replace(/\s*[\r\n\u2028\u2029]+\s*/g, ' ');

function list(lines: string[], cap = CAP): string[] {
  const flat = lines.map(oneLine);
  if (!flat.length) return ['_None._'];
  return flat.length > cap ? [...flat.slice(0, cap), `- _(+${flat.length - cap} more in snapshot.json)_`] : flat;
}

/** The body of the Facts section. Pure function of the snapshot. */
export function renderFactsBody(s: RepoSnapshot): string {
  const out: string[] = [];
  const facts = (...categories: string[]) => s.facts.filter((f) => categories.includes(f.category));
  const bullet = (f: { statement: string; source: FactSource }) => `- ${oneLine(f.statement)} _(${cite(f.source)})_`;

  out.push('## Facts');
  out.push('');
  out.push(
    `Read from commit \`${s.commit.slice(0, 12)}\` (snapshot \`${shortSnapshotId(s.hash)}\`). Every line cites \`path@blob[:lines]\` at that commit. ` +
      'Uncommitted changes are never included; anything that could not be proven is listed under "Not confirmed".',
  );
  out.push('');
  out.push('### Layout');
  out.push(...list(facts('layout').map(bullet)));
  out.push('');
  out.push('### Workspace packages');
  out.push(...list(facts('workspace').map(bullet)));
  out.push('');
  out.push('### Packages and entry points');
  out.push(...list(facts('package', 'entry-point').map(bullet)));
  out.push('');
  out.push('### Commands');
  out.push(...list(facts('command').map(bullet)));
  out.push('');
  const scripts = facts('script');
  out.push(`### Scripts (${scripts.length})`);
  out.push(...list(scripts.map(bullet)));
  out.push('');
  out.push('### Language and tool versions (declared requirements, not installed versions)');
  out.push(...list(facts('language', 'version').map(bullet)));
  out.push('');

  const deps = s.dependencies;
  const count = (rel: string) => deps.filter((d) => d.relation === rel).length;
  out.push(`### Dependencies (${deps.length} declared)`);
  out.push(
    `Declared and installed versions are separate. ${count('match')} installed versions satisfy their declared range, ${count('mismatch')} do not, ${count('unchecked')} could not be checked.`,
  );
  out.push('');
  const drift = deps.filter((d) => d.relation === 'mismatch');
  out.push('**Version drift (installed does not satisfy declared):**');
  out.push(...list(drift.map((d) => `- ${d.statement} _(declared: ${cite(d.declared.source)}${d.installed ? `; installed: ${cite(d.installed.source)}` : ''})_`)));
  out.push('');
  const byWorkspace = new Map<string, typeof deps>();
  for (const d of deps) {
    if (!byWorkspace.has(d.workspace)) byWorkspace.set(d.workspace, []);
    if (d.installedStatus !== 'workspace-link') byWorkspace.get(d.workspace)!.push(d);
  }
  for (const w of [...byWorkspace.keys()].sort()) {
    const mine = byWorkspace.get(w)!;
    out.push(oneLine(`**\`${w}\`** — ${mine.length} registry dependencies`));
    out.push(
      ...list(
        mine.map(
          (d) =>
            `- \`${d.name}\` declared \`${d.declared.spec}\` (${d.section}) _(${cite(d.declared.source)})_; installed ${d.installed ? `\`${d.installed.version}\` _(${cite(d.installed.source)})_` : `unknown (${d.installedStatus})`}`,
        ),
        40,
      ),
    );
    out.push('');
  }

  const conv = (status: Convention['status']) => s.conventions.filter((c) => c.status === status);
  out.push('### Conventions — confirmed');
  out.push('Confirmed means a config file sets it, or an exhaustive count over the tracked files is 100%.');
  out.push(...list(conv('confirmed').map((c) => `- ${c.statement} _(${cite(c.source)})_`)));
  out.push('');
  out.push('### Conventions — unconfirmed (measurements, not facts)');
  out.push(
    ...list(
      conv('unconfirmed').map((c) => {
        const ex = c.counterexamples.length ? ` Not followed in: ${c.counterexamples.map(cite).join(', ')}.` : '';
        return `- ${c.statement}.${ex}`;
      }),
    ),
  );
  out.push('');
  out.push('### Not confirmed');
  out.push(...list(s.unconfirmed.map((u) => `- ${u.statement} _(${cite(u.source)})_`)));
  return out.join('\n');
}

const count = (text: string, re: RegExp) => (text.match(re) ?? []).length;
const BEGIN_ANY = /^<!-- turbine:facts begin [^>]*? -->\r?$/gm;
const END_ANY = /^<!-- turbine:facts end -->\r?$/gm;

/** Which marker the user has to restore, or undefined when there is no section or exactly one intact section. */
function damagedMarker(text: string): string | undefined {
  const begins = count(text, BEGIN_ANY);
  const ends = count(text, END_ANY);
  if (begins === 0 && ends === 0) return undefined;
  if (begins === 1 && ends === 1 && SECTION.test(text)) return undefined;
  if (begins === 0) return 'the "<!-- turbine:facts begin … -->" line';
  if (ends === 0) return 'the "<!-- turbine:facts end -->" line';
  if (begins > 1 || ends > 1) return 'a single "turbine:facts begin" / "turbine:facts end" pair (the file has more than one)';
  return 'the "turbine:facts end" line, which must come after the "begin" line';
}

/** Repair is only safe when the section's boundaries are unambiguous; otherwise say what to restore. */
function assertMarkersIntact(text: string): void {
  const missing = damagedMarker(text);
  if (missing) {
    throw new Error(
      `.turbine/context/PROJECT.md has a damaged generated Facts section; restore ${missing} (or delete the whole section), then run: turbine understand`,
    );
  }
}

function renderProjectMd(s: RepoSnapshot, existing: string | undefined): string {
  const body = renderFactsBody(s);
  const marker = `<!-- turbine:facts begin snapshot=${s.hash} commit=${s.commit} content=${contentHashText(body)} -->`;
  // Keep the file's own line-ending style so the section does not leave the file with mixed endings.
  const eol = existing?.includes('\r\n') ? '\r\n' : '\n';
  const section = `${marker}\n${body}\n<!-- turbine:facts end -->`.split('\n').join(eol);
  if (existing) assertMarkersIntact(existing);
  if (existing && SECTION.test(existing)) return existing.replace(SECTION, () => section);
  if (existing) return `${existing.replace(/\r?\n*$/, eol)}${eol}${section}${eol}`;
  return `${FILE_HEADER}\n# Project context\n\n${section}\n`;
}

function attrs(raw: string): Record<string, string> {
  return Object.fromEntries([...raw.matchAll(/(\w+)=(\S+)/g)].map((m) => [m[1]!, m[2]!]));
}

/** True when both generated files exist and match the snapshot exactly. */
export function contextFilesCurrent(projectRoot: string, s: RepoSnapshot): boolean {
  const p = contextPaths(projectRoot);
  try {
    if (readRegular(p.snapshot) !== `${JSON.stringify(s, null, 2)}\n`) return false;
    const project = readRegular(p.project);
    if (project === undefined || damagedMarker(project)) return false;
    const m = SECTION.exec(project);
    if (!m) return false;
    const a = attrs(m[1]!);
    const body = bodyOf(m);
    return body === renderFactsBody(s) && a.snapshot === s.hash && a.commit === s.commit && a.content === contentHashText(body);
  } catch {
    return false;
  }
}

/** Contents of a regular file, undefined if it does not exist; throws for a symlink, directory or other non-file. */
function readRegular(file: string): string | undefined {
  let st;
  try {
    st = lstatSync(file);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw e;
  }
  if (!st.isFile()) throw new Error(`${file} is not a regular file (a symlink or directory)`);
  return readFileSync(file, 'utf8');
}

/**
 * Generated files live inside the repository, which the repository's author controls. A checked-out
 * symlink at a generated path would otherwise make a write land on whatever it points to. So: the
 * directories must be real directories, the destination must not be a symlink, and the file is
 * written to a new exclusive temp file and renamed into place (rename replaces the name, never the
 * target of a link).
 */
function assertRealDirs(projectRoot: string, dir: string): void {
  for (const d of [join(projectRoot, '.turbine'), dir]) {
    if (!existsSync(d) && !isLink(d)) continue;
    if (!lstatSync(d).isDirectory()) throw new Error(`${d} is not a real directory (a symlink?); refusing to write generated context through it`);
  }
}

function isLink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

function writeAtomic(file: string, content: string): void {
  let mode: number | undefined; // undefined: a new file gets 0666 minus the user's umask, as any new file does
  if (isLink(file)) throw new Error(`${file} is not a regular file (a symlink?); refusing to write generated context through it`);
  if (existsSync(file)) {
    const st = lstatSync(file);
    if (!st.isFile()) throw new Error(`${file} is not a regular file (a symlink?); refusing to write generated context through it`);
    mode = st.mode & 0o777; // regenerating must not make a private file readable by more users
  }
  const tmp = join(dirname(file), `.${process.pid}-${Date.now()}-${Math.random().toString(36).slice(2)}.tmp`);
  // O_EXCL: never follows a link, never reuses a file. An existing file's mode is applied before any
  // content is written, so the replacement is never readable by more users than the original.
  const fd = openSync(tmp, 'wx', mode === undefined ? 0o666 : 0o600);
  try {
    try {
      if (mode !== undefined) fchmodSync(fd, mode);
      writeFileSync(fd, content, 'utf8'); // writes every byte (a bare write may be partial)
    } finally {
      closeSync(fd);
    }
    renameSync(tmp, file); // only a complete file is ever published
  } catch (e) {
    rmSync(tmp, { force: true });
    throw e;
  }
}

/**
 * One publisher per project at a time. The lock is an exclusive file holding the owner's pid; a lock whose
 * owner is gone is removed and taken over. A live owner means another `turbine understand` is writing.
 */
function withPublishLock<T>(projectRoot: string, fn: () => T): T {
  const lock = join(contextPaths(projectRoot).dir, '.publish.lock');
  const acquire = () => {
    const fd = openSync(lock, 'wx');
    writeFileSync(fd, String(process.pid), 'utf8');
    closeSync(fd);
  };
  try {
    acquire();
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e;
    const owner = Number(readFileSync(lock, 'utf8').trim());
    let alive = true;
    if (Number.isInteger(owner) && owner > 0) {
      try {
        process.kill(owner, 0);
      } catch (err) {
        alive = (err as NodeJS.ErrnoException).code !== 'ESRCH';
      }
    } else alive = false;
    if (alive) throw new Error('another `turbine understand` is writing the project context; wait for it to finish and retry');
    rmSync(lock, { force: true });
    acquire();
  }
  try {
    return fn();
  } finally {
    rmSync(lock, { force: true });
  }
}

/**
 * Write snapshot.json and the Facts section of PROJECT.md. Returns the files written.
 * `stillCurrent` is asked, under the lock and after everything is rendered, whether the snapshot is still
 * the one for HEAD. If HEAD moved, nothing is published (the caller rebuilds for the new HEAD).
 */
export function writeContextFiles(projectRoot: string, s: RepoSnapshot, stillCurrent: () => boolean = () => true): string[] {
  const p = contextPaths(projectRoot);
  assertRealDirs(projectRoot, p.dir);
  mkdirSync(p.dir, { recursive: true });
  assertRealDirs(projectRoot, p.dir);
  return withPublishLock(projectRoot, () => {
    // Build everything first so a damaged PROJECT.md stops the run before anything is written.
    const project = renderProjectMd(s, readRegular(p.project));
    if (!stillCurrent()) throw new Error('HEAD changed while the project context was being written; nothing was published. Run again.');
    writeAtomic(p.snapshot, `${JSON.stringify(s, null, 2)}\n`);
    writeAtomic(p.project, project);
    ensureContextIgnored(projectRoot);
    return [p.snapshot, p.project];
  });
}

/**
 * The generated files cite the commit they were built from, so committing them would move
 * HEAD and make them stale again. Keep them out of git. Returns true if the rule was added.
 */
export function ensureContextIgnored(projectRoot: string): boolean {
  const file = join(projectRoot, '.turbine', '.gitignore');
  const text = readRegular(file);
  if (text !== undefined && contextIgnored(text)) return false;
  // Already ignored by git through some other rule: nothing to add. (undefined: not a repository.)
  if (isGitIgnored(projectRoot, GENERATED_PROBE) === true) return false;
  mkdirSync(dirname(file), { recursive: true });
  writeAtomic(file, `${(text ?? '').replace(/\n*$/, text ? '\n' : '')}${CONTEXT_DIR}/\n`);
  return true;
}

/** A path inside the generated directory, used to ask git whether its files are ignored. */
const GENERATED_PROBE = `.turbine/${CONTEXT_DIR}/snapshot.json`;

/** Git applies ignore rules in order, so the LAST rule that mentions the directory decides. */
function contextIgnored(gitignore: string): boolean {
  let ignored = false;
  for (const raw of gitignore.split('\n')) {
    const line = raw.trim();
    if (['context/', '/context/', 'context', '/context'].includes(line)) ignored = true;
    else if (['!context/', '!/context/', '!context', '!/context'].includes(line)) ignored = false;
  }
  return ignored;
}

/** `turbine lint`: report hand edits to the generated project context. */
export function lintProjectContext(projectRoot: string): LintIssue[] {
  const p = contextPaths(projectRoot);
  const issues: LintIssue[] = [];
  const exists = (f: string) => existsSync(f) || isLink(f);
  for (const d of [join(projectRoot, '.turbine'), p.dir]) {
    if (!exists(d)) continue;
    if (isLink(d) || !lstatSync(d).isDirectory()) {
      issues.push({ level: 'error', file: d.slice(projectRoot.length + 1), message: 'is not a real directory (a symlink or a file); generated context cannot be written or checked through it' });
      return issues;
    }
  }
  const tracked = trackedPaths(projectRoot, `.turbine/${CONTEXT_DIR}/`);
  for (const t of tracked) {
    issues.push({ level: 'warning', file: t, message: 'is tracked by git; generated context should not be committed (it cites the commit it was built from). Run: git rm --cached -r .turbine/context' });
  }
  const hasSnapshot = exists(p.snapshot);
  const hasProject = exists(p.project);
  if (!hasSnapshot && !hasProject) return issues;
  if (isGitIgnored(projectRoot, GENERATED_PROBE) === false) {
    issues.push({ level: 'error', file: '.turbine/.gitignore', message: 'git does not ignore .turbine/context/ (a later rule un-ignores it), so the generated files would be committed; remove that rule or add `.turbine/context/` after it' });
  }

  let snapshot: RepoSnapshot | undefined;
  if (!hasSnapshot) issues.push({ level: 'error', file: 'snapshot.json', message: 'missing; run: turbine understand' });
  else {
    try {
      const raw: unknown = JSON.parse(readRegular(p.snapshot) ?? '');
      const parsed = hasUnsafeKey(raw) ? undefined : RepoSnapshotSchema.safeParse(raw);
      if (parsed?.success) snapshot = parsed.data;
      else if (!parsed) issues.push({ level: 'error', file: 'snapshot.json', message: 'contains a "__proto__" key, which is refused; run: turbine understand' });
      else if (!parsed.success) issues.push({ level: 'error', file: 'snapshot.json', message: `was edited by hand or is corrupt (${parsed.error.issues[0]?.message ?? 'invalid'}); run: turbine understand` });
    } catch (e) {
      issues.push({ level: 'error', file: 'snapshot.json', message: `is not valid JSON (${(e as Error).message}); run: turbine understand` });
    }
  }

  if (!hasProject) {
    issues.push({ level: 'error', file: 'PROJECT.md', message: 'missing; run: turbine understand' });
    return issues;
  }
  let text: string;
  try {
    text = readRegular(p.project) ?? '';
  } catch (e) {
    issues.push({ level: 'error', file: 'PROJECT.md', message: `cannot be read (${(e as Error).message}); restore it or run: turbine understand` });
    return issues;
  }
  const damaged = damagedMarker(text);
  const m = SECTION.exec(text);
  if (damaged || !m || !BEGIN.test(text)) {
    issues.push({
      level: 'error',
      file: 'PROJECT.md',
      message: damaged
        ? `the generated Facts section is damaged; restore ${damaged}, or run: turbine understand after deleting the section`
        : 'the generated Facts section is missing or its markers were edited; run: turbine understand',
    });
    return issues;
  }
  const a = attrs(m[1]!);
  const body = bodyOf(m);
  if (a.content !== contentHashText(body)) {
    issues.push({ level: 'error', file: 'PROJECT.md', message: 'the Facts section was edited by hand (content hash mismatch); manual edits are overwritten by: turbine understand' });
  } else if (snapshot && a.commit !== snapshot.commit) {
    issues.push({ level: 'error', file: 'PROJECT.md', message: 'the commit in the Facts marker was edited by hand and does not match snapshot.json; run: turbine understand' });
  } else if (snapshot && a.snapshot !== snapshot.hash) {
    issues.push({ level: 'error', file: 'PROJECT.md', message: 'the Facts section comes from a different snapshot than snapshot.json; run: turbine understand' });
  } else if (snapshot && body !== renderFactsBody(snapshot)) {
    issues.push({ level: 'error', file: 'PROJECT.md', message: 'the Facts section does not match snapshot.json (edited by hand); run: turbine understand' });
  }
  return issues;
}
